"""Real, end-to-end tests for InkscapeAdapter, ImageMagickAdapter,
KritaAdapter, FFmpegAdapter, and GimpAdapter — an actual SVG generated on
disk, exported through the real Inkscape binary, then resized/converted
through the real ImageMagick/Krita/FFmpeg/GIMP binaries. No mocks."""
import os
import shutil
import subprocess
import sys
import tempfile

from adapters.inkscape_adapter import InkscapeAdapter
from adapters.imagemagick_adapter import ImageMagickAdapter
from adapters.krita_adapter import KritaAdapter
from adapters.ffmpeg_adapter import FFmpegAdapter
from adapters.gimp_adapter import GimpAdapter

TEST_SVG = """<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200" viewBox="0 0 200 200">
  <rect width="200" height="200" fill="#1a1a2e"/>
  <circle cx="100" cy="100" r="80" fill="#e94560"/>
</svg>"""


def run():
    tmp_dir = tempfile.mkdtemp(prefix="koba_test_adapters_")
    try:
        svg_path = os.path.join(tmp_dir, "test_icon.svg")
        with open(svg_path, "w") as f:
            f.write(TEST_SVG)

        inkscape = InkscapeAdapter()
        assert inkscape.detect(), "Inkscape should be detected (confirmed installed on this machine)"
        assert "Inkscape" in inkscape.version()

        png_path = os.path.join(tmp_dir, "test_icon.png")
        inkscape.export_png(svg_path, png_path, width=256)
        assert os.path.isfile(png_path)
        assert os.path.getsize(png_path) > 0

        variants = inkscape.export_variants(svg_path, tmp_dir, "test_icon", widths=(64, 128))
        assert set(variants.keys()) == {64, 128}
        for path in variants.values():
            assert os.path.isfile(path)

        magick = ImageMagickAdapter()
        assert magick.detect(), "ImageMagick should be detected (confirmed installed on this machine)"
        assert "ImageMagick" in magick.version()

        resized_path = os.path.join(tmp_dir, "resized.png")
        magick.resize(png_path, resized_path, width=64)
        assert os.path.isfile(resized_path)

        webp_path = os.path.join(tmp_dir, "converted.webp")
        magick.convert_format(png_path, webp_path)
        assert os.path.isfile(webp_path)

        thumb_path = os.path.join(tmp_dir, "thumb.png")
        magick.generate_thumbnail(png_path, thumb_path, size=32)
        assert os.path.isfile(thumb_path)

        # source is 256px — a 2048 mip must be skipped (no upscaling), 128/64 must exist
        mip_dir = os.path.join(tmp_dir, "mips")
        os.makedirs(mip_dir)
        mips = magick.create_mip_chain(png_path, mip_dir, sizes=(2048, 128, 64))
        assert 2048 not in mips, "create_mip_chain must not upscale beyond the source resolution"
        assert set(mips.keys()) == {128, 64}
        for path in mips.values():
            assert os.path.isfile(path)

        # --- KritaAdapter: real headless export via Krita's own CLI ---
        krita = KritaAdapter()
        assert krita.detect(), "Krita should be detected (confirmed installed on this machine, 2026-09-30)"
        assert "krita" in krita.version().lower()

        krita_out_path = os.path.join(tmp_dir, "krita_export.jpg")
        krita.export_to(png_path, krita_out_path, timeout=90)
        assert os.path.isfile(krita_out_path)
        assert os.path.getsize(krita_out_path) > 0

        try:
            krita.export_to(os.path.join(tmp_dir, "does_not_exist.kra"), krita_out_path)
            assert False, "export_to must raise on a missing source file, not silently no-op"
        except FileNotFoundError:
            pass

        # --- FFmpegAdapter: real transcode/frame-extract/probe, against a
        # synthetic clip generated by ffmpeg's own lavfi test source (no
        # external video file needed, no mock) ---
        ffmpeg = FFmpegAdapter()
        assert ffmpeg.detect(), "FFmpeg should be detected (confirmed installed on this machine, 2026-09-30)"
        assert "ffmpeg version" in ffmpeg.version().lower()

        clip_path = os.path.join(tmp_dir, "clip.mp4")
        subprocess.run(
            [ffmpeg._executable(), "-y", "-f", "lavfi", "-i", "testsrc=duration=2:size=64x64:rate=10", clip_path],
            capture_output=True, text=True, timeout=30, check=True,
        )
        assert os.path.isfile(clip_path)

        webm_path = os.path.join(tmp_dir, "clip.webm")
        ffmpeg.transcode(clip_path, webm_path)
        assert os.path.isfile(webm_path)
        assert os.path.getsize(webm_path) > 0

        frame_path = os.path.join(tmp_dir, "frame.png")
        ffmpeg.extract_frame(clip_path, frame_path, timestamp="00:00:01")
        assert os.path.isfile(frame_path)
        assert os.path.getsize(frame_path) > 0

        duration = ffmpeg.get_duration(clip_path)
        assert 1.5 < duration < 2.5, f"expected ~2s, got {duration}"

        try:
            ffmpeg.transcode(os.path.join(tmp_dir, "nope.mp4"), webm_path)
            assert False, "transcode must raise on a missing source file, not silently no-op"
        except FileNotFoundError:
            pass

        # --- GimpAdapter: real headless export via GIMP's own Python-Fu
        # batch CLI (confirmed live: GIMP 3.x needs --batch-interpreter
        # explicitly and a top-level --quit flag, not a -b batch command,
        # to exit cleanly — see adapters/gimp_adapter.py's docstring) ---
        gimp = GimpAdapter()
        assert gimp.detect(), "GIMP should be detected (Flatpak wrapper, confirmed installed)"
        assert "image manipulation" in gimp.version().lower()

        gimp_out_path = os.path.join(tmp_dir, "gimp_export.jpg")
        gimp.export_to(png_path, gimp_out_path, timeout=90)
        assert os.path.isfile(gimp_out_path)
        assert os.path.getsize(gimp_out_path) > 0

        try:
            gimp.export_to(os.path.join(tmp_dir, "does_not_exist.xcf"), gimp_out_path)
            assert False, "export_to must raise on a missing source file, not silently no-op"
        except FileNotFoundError:
            pass

        return True
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


if __name__ == "__main__":
    ok = run()
    print("test_adapters: PASS" if ok else "test_adapters: FAIL")
    sys.exit(0 if ok else 1)
